CREATE TABLE goals (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(255) NOT NULL,
    description VARCHAR2(2000),
    dimension VARCHAR2(20) NOT NULL CHECK (dimension IN ('environmental', 'social', 'governance')),
    company_id NUMBER NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
);

CREATE INDEX idx_goals_company_dimension ON goals(company_id, dimension);
